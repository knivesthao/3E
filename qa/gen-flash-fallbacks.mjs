// Generates 100 decorative flashcard fallback images as inline SVG data
// URIs into src/lib/flash-fallbacks.ts. Procedural on purpose: abstract
// background shapes need no model, so this costs $0, works offline, and
// never touches the factory's Modal/Meta credits.
//
// Palette follows src/index.css: neutral by design — white surfaces, stone
// text, one muted teal accent. No saturated hues, nothing carried by color.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Seeded PRNG so the set is stable across runs.
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const BACKGROUNDS = ['#fafaf9', '#f5f5f4', '#f0fdfa', '#e7e5e4', '#f5f5f4', '#fafaf9'];
// Muted shape tones only: soft stone, pale teal, deep teal at low opacity.
const TONES = ['#d6d3d1', '#a8a29e', '#99f6e4', '#5eead4', '#ccfbf1', '#134e4a', '#e7e5e4'];

function pick(rand, xs) {
  return xs[Math.floor(rand() * xs.length)];
}

function shapes(rand) {
  const out = [];
  const tone = () => pick(rand, TONES);
  const opacity = () => (0.4 + rand() * 0.4).toFixed(1);
  const count = 3 + Math.floor(rand() * 2);
  for (let i = 0; i < count; i++) {
    const kind = Math.floor(rand() * 5);
    const cx = Math.floor(rand() * 640);
    const cy = Math.floor(rand() * 360);
    if (kind === 0) {
      const r = 24 + Math.floor(rand() * 110);
      out.push(`<circle cx="${cx}" cy="${cy}" r="${r}" fill="${tone()}" opacity="${opacity()}"/>`);
    } else if (kind === 1) {
      const r = 20 + Math.floor(rand() * 70);
      const w = 8 + Math.floor(rand() * 18);
      out.push(`<circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${tone()}" stroke-width="${w}" opacity="${opacity()}"/>`);
    } else if (kind === 2) {
      const w = 60 + Math.floor(rand() * 160);
      const h = 40 + Math.floor(rand() * 110);
      const rx = 12 + Math.floor(rand() * 30);
      const rot = Math.floor(rand() * 90) - 45;
      out.push(`<rect x="${cx - w / 2}" y="${cy - h / 2}" width="${w}" height="${h}" rx="${rx}" fill="${tone()}" opacity="${opacity()}" transform="rotate(${rot} ${cx} ${cy})"/>`);
    } else if (kind === 3) {
      // Dotted row: quiet texture, never near the center word zone.
      const n = 3 + Math.floor(rand() * 3);
      const gap = 26 + Math.floor(rand() * 20);
      const x0 = Math.floor(rand() * 640);
      const y0 = rand() < 0.5 ? 24 + Math.floor(rand() * 60) : 276 + Math.floor(rand() * 60);
      const r = 4 + Math.floor(rand() * 6);
      let dots = '';
      for (let d = 0; d < n; d++) dots += `<circle cx="${x0 + d * gap}" cy="${y0}" r="${r}" fill="${tone()}" opacity="${opacity()}"/>`;
      out.push(dots);
    } else {
      // Soft wave band across the card.
      const y = 60 + Math.floor(rand() * 240);
      const amp = 14 + Math.floor(rand() * 26);
      const h = 30 + Math.floor(rand() * 60);
      out.push(`<path d="M-10 ${y} Q 160 ${y - amp}, 320 ${y} T 650 ${y} L650 ${y + h} L-10 ${y + h} Z" fill="${tone()}" opacity="${opacity()}"/>`);
    }
  }
  return out.join('');
}

function card(i) {
  const rand = mulberry32(0x3e000 + i * 7919);
  const bg = pick(rand, BACKGROUNDS);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 360">` +
    `<rect width="640" height="360" fill="${bg}"/>${shapes(rand)}</svg>`;
  return 'data:image/svg+xml,' + encodeURIComponent(svg);
}

const items = Array.from({ length: 100 }, (_, i) => `  ${JSON.stringify(card(i))},`).join('\n');
const out =
  `// GENERATED by qa/gen-flash-fallbacks.mjs — do not edit. Run the script\n` +
  `// again to regenerate the set (seeded, so output is stable).\n` +
  `export const FLASH_FALLBACKS: string[] = [\n${items}\n];\n`;

const root = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(root, '..', 'src', 'lib', 'flash-fallbacks.ts'), out);
console.log(`wrote 100 fallbacks to src/lib/flash-fallbacks.ts`);
