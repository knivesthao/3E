const ORDER: Level[] = ['A1', 'A2', 'B1', 'B2'];

// Tunables: minimum known-word coverage, max scene words per level.
export const LEVEL_COVERAGE = 0.9;
export const SCENE_MAX_WORDS: Record<Level, number> = { A1: 40, A2: 60, B1: 80, B2: 100 };

const LISTS: Record<Level, string[]> = { A1, A2, B1, B2 };

function allowedSet(level: Level, extraWords: string[]): Set<string> {
  const set = new Set<string>();
  for (const l of ORDER) {
    for (const w of LISTS[l]) set.add(w);
    if (l === level) break;
  }
  for (const w of extraWords) set.add(w.toLowerCase());
  return set;
}

export function tokenize(text: string): string[] {
  return (text.toLowerCase().match(/[a-z]+(?:'[a-z]+)?/g) ?? []).filter((t) => t.length > 0);
}

// Naive stemmer for inflected forms (runs→run, walked→walk, flies→fly,
// going→go). Keeps the gate from failing everyday conjugations; doubling
// forms (running→runn) stay unknown and get reported.
export function stem(token: string): string {
  if (token.endsWith('ies') && token.length > 4) return `${token.slice(0, -3)}y`;
  for (const suffix of ['ing', 'ed', 'es', 's', 'd']) {
    // 'ing' may leave a 2-letter stem (going→go, doing→do, being→be);
    // shorter suffixes need >= 3 so short words (was, red, as) survive.
    const minStem = suffix === 'ing' ? 2 : 3;
    if (token.endsWith(suffix) && token.length - suffix.length >= minStem) {
      return token.slice(0, -suffix.length);
    }
  }
  return token;
}

function knownWord(allowed: Set<string>, token: string): boolean {
  return allowed.has(token) || allowed.has(stem(token));
}

export interface LevelResult {
  passed: boolean;
  coverage: number;
  words: number;
  maxWords: number;
  unknown: string[];
}

export function checkLevel(text: string, level: Level, extraWords: string[] = []): LevelResult {
  const tokens = tokenize(text);
  const allowed = allowedSet(level, extraWords);
  const unknownSet = new Set<string>();
  let known = 0;
  for (const t of tokens) {
    if (knownWord(allowed, t)) known++;
    else unknownSet.add(t);
  }
  const coverage = tokens.length === 0 ? 1 : known / tokens.length;
  const words = tokens.length;
  const maxWords = SCENE_MAX_WORDS[level];
  return {
    passed: coverage >= LEVEL_COVERAGE && words <= maxWords,
    coverage,
    words,
    maxWords,
    unknown: [...unknownSet].slice(0, 20),
  };
}
